"""Write docs/tool-reference.md: every tool with its inputs, permission and output fields.

Inputs and permissions come from the tool registry. Output fields come from calling each
read-only tool once against the running stack (top-level keys of the returned data), so the
table cannot drift from the code. Changing tools are never executed; their outputs are the
fields of their success result, listed by hand below.

    python scripts/tool_reference.py          # needs the stack running (see README)
"""

from __future__ import annotations

import json
from pathlib import Path

from agent.config import load_config, load_dotenv
from agent.llm import LLMClient
from agent.orchestrator import Orchestrator
from agent.registry import build_registry
from agent.safety import ConfirmationManager

CHANGING_OUTPUT = {
    "dvc_checkout_version": "checked_out, dvc_file, md5",
    "airflow_trigger_dag": (
        "triggered, dag_id, dag_run_id, state, run_type, queued_at, start_date, end_date, "
        "duration_s, conf, triggered_by"
    ),
    "k8s_restart_deployment": "restarted, namespace, restarted_at",
    "k8s_scale_deployment": "scaled, namespace, from, to",
}
EXPERIMENT = "mlops-agent-demo"


def main() -> None:
    load_dotenv()
    config = load_config()
    confirmations = ConfirmationManager(config.confirm_ttl_s)
    registry = build_registry(config, confirmations)
    agent = Orchestrator(config, LLMClient(config), registry, confirmations)

    def call(name: str, **args):
        from agent.llm import ToolCall

        return agent._dispatch(ToolCall(id="ref", name=name, arguments=args))

    runs = call("mlflow_list_runs", experiment=EXPERIMENT, limit=2)
    run_ids = [r["run_id"] for r in (runs.data or {}).get("runs", [])]
    dag_runs = call("airflow_dag_runs", dag_id="training_pipeline", limit=1)
    dag_run_id = ((dag_runs.data or {}).get("runs") or [{}])[0].get("dag_run_id")
    pods = call("k8s_list_pods")
    pod = ((pods.data or {}).get("pods") or [{}])[0].get("name")
    samples = {
        "dvc_compare_versions": {"rev_a": "data-v1", "rev_b": "data-v2"},
        "dvc_reproduce_instructions": {"rev": "data-v1"},
        "mlflow_list_runs": {"experiment": EXPERIMENT},
        "mlflow_get_run": {"run_id": run_ids[0] if run_ids else "none"},
        "mlflow_best_run": {"experiment": EXPERIMENT, "metric": "f1"},
        "mlflow_compare_runs": {"run_ids": run_ids},
        "mlflow_compare_experiments": {"experiments": [EXPERIMENT, "Default"], "metric": "f1"},
        "airflow_dag_runs": {"dag_id": "training_pipeline"},
        "airflow_run_detail": {"dag_id": "training_pipeline", "run_id": dag_run_id},
        "airflow_failed_tasks": {"dag_id": "training_pipeline", "run_id": dag_run_id},
        "airflow_task_logs": {
            "dag_id": "training_pipeline",
            "run_id": dag_run_id,
            "task_id": "quality_gate",
        },
        "k8s_pod_status": {"pod": pod},
        "k8s_pod_logs": {"pod": pod},
        "k8s_deployed_version": {"deployment": "inference-api"},
    }

    lines = [
        "# Tool reference",
        "",
        "Generated by `python scripts/tool_reference.py` from the tool registry and one call to each",
        "read-only tool on the running stack. Every tool returns the envelope",
        "`{ok, tool, data, error, duration_ms}`; the output column lists the top-level fields of `data`.",
        "",
        "Permission levels: **read** runs immediately. **confirmed change** first returns",
        "`confirmation_required` and a token, and runs only after the user types `confirm <token>`.",
        "All Kubernetes tools are limited to the allowlisted namespace; Airflow trigger to the allowlisted DAG.",
        "",
    ]
    groups = {"dvc": "DVC", "mlflow": "MLflow", "airflow": "Airflow", "k8s": "Kubernetes"}
    for prefix, title in groups.items():
        lines += [
            f"## {title}",
            "",
            "| Tool | Inputs | Output fields | Permission |",
            "|---|---|---|---|",
        ]
        for name, spec in sorted(registry.items()):
            if not name.startswith(prefix + "_"):
                continue
            props = spec.parameters.get("properties", {})
            required = set(spec.parameters.get("required", []))
            inputs = (
                ", ".join(
                    f"`{k}`{'*' if k in required else ''}: {v.get('type', 'any')}"
                    for k, v in props.items()
                )
                or "none"
            )
            if spec.mutating:
                output = CHANGING_OUTPUT.get(name, "see tool")
                perm = "confirmed change"
            else:
                result = call(name, **samples.get(name, {}))
                data = result.data
                if result.ok and isinstance(data, dict):
                    output = ", ".join(f"`{k}`" for k in data)
                else:
                    output = f"(not captured: {result.error})"
                perm = "read"
            lines.append(f"| `{name}` | {inputs} | {output} | {perm} |")
        lines.append("")
    lines.append("`*` marks a required input.")
    Path("docs/tool-reference.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps({"tools": len(registry)}))


if __name__ == "__main__":
    main()
